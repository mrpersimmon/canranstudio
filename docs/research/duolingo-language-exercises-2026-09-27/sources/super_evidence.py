    for n, action, result in rows(STORY) + rows(REVIEW) + rows(RADIO):
        origins = list(capture.glob(f'{n:03d}-*.png'))
        assert len(origins) == 1, (n, origins)
        origin = origins[0]
        dest = root / 'assets/flows' / f'{n:03d}.png'
        shutil.copy2(origin, dest)
        with Image.open(dest) as im:
            w, h = im.size
        session = 'C' if n < 400 else 'D' if n < 500 else 'E'
        source = {'C':'https://www.duolingo.com/stories/en-zh-taxi-ride?mode=read&practiceHubStory=featured', 'D':'https://www.duolingo.com/practice-hub/unit-rewind', 'E':'https://www.duolingo.com/lesson/unit/55/level/3'}[session]
